import {registerHooks} from 'node:module';
import {readFileSync,writeFileSync} from 'node:fs';
registerHooks({load(url,ctx,next){if(url.endsWith('?url'))return {format:'module',source:`export default ${JSON.stringify(url.slice(0,-4))}`,shortCircuit:true};return next(url,ctx);}});
const {characters}=await import('../src/data/characters.js');
const metadata={};
for(const [key,c] of Object.entries(characters)){
  const urls=[c.url,...c.appendUrls.slice(0,c.comboRoutes?-1:undefined)];
  metadata[key]={start:c.comboArtStart??c.frameRects.length,y:urls.reduce((sum,url)=>sum+readFileSync(new URL(url)).readUInt32BE(20),0)};
}
writeFileSync(new URL('../src/data/comboArtLayout.js',import.meta.url),`// Existing source stacks stay in their original order. Generated by scripts/register-combo-art.mjs.\nexport const COMBO_ART_LAYOUT=${JSON.stringify(metadata,null,2)};\n`);
